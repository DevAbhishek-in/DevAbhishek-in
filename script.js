/* ---------- Search and filtering: results are actual configured items ---------- */
function normalizeText(value) {
  return String(value || "").toLowerCase().replace(/[^a-z0-9 ]/g, " ").replace(/\s+/g, " ").trim();
}

function textScore(query, fields) {
  const q = normalizeText(query);
  if (!q) return 0;
  const haystack = normalizeText(fields.join(" "));
  if (haystack.includes(q)) return 5;
  const terms = q.split(" ");
  const found = terms.filter((term) => haystack.includes(term)).length;
  return found === terms.length ? 3 : found ? 1 : 0;
}

function searchLibrary(query, appId = "") {
  const q = normalizeText(query);
  if (!q) return [];
  const results = [];
  APP_DATA.filter((app) => hasRecordId(app) && (!appId || app.id === appId)).forEach((app) => {
    const score = textScore(q, [app.name, app.description, ...(app.categories || []), ...(app.tags || [])]);
    if (score) results.push({ kind: "app", id: app.id, appId: app.id, title: app.name, detail: `${appStatus(app) === "available" ? "Available" : "Coming Soon"} · app setup`, icon: app.icon, score });
  });
  SETUP_GUIDE_DATA.filter((guide) => hasRecordId(guide) && (!appId || guide.appId === appId)).forEach((guide) => {
    const score = textScore(q, [guide.title, guide.description, guide.category, guide.app, ...(guide.keywords || [])]);
    if (score) results.push({ kind: "guide", id: guide.id, appId: guide.appId, title: guide.title, detail: `${guide.app} · Setup guide`, icon: "▣", score: score + 0.2, status: guide.status });
  });
  TUTORIAL_DATA.filter((tutorial) => hasRecordId(tutorial) && (!appId || tutorial.appId === appId)).forEach((tutorial) => {
    const commands = (tutorial.commands || []).flatMap((item) => [item.label || "", item.code || ""]);
    const score = textScore(q, [tutorial.title, tutorial.description, tutorial.category, tutorial.app, ...(tutorial.keywords || []), ...commands]);
    if (score) results.push({ kind: "tutorial", id: tutorial.id, appId: tutorial.appId, title: tutorial.title, detail: `${tutorial.app} · Tutorial`, icon: "▷", score: score + 0.1, status: tutorial.status });
  });
  return results.sort((a, b) => b.score - a.score || a.title.localeCompare(b.title)).slice(0, 10);
}

function renderSearchResults(containerId, clearId, query, appId = "") {
  const container = document.getElementById(containerId);
  const clear = document.querySelector(`[data-clear-search="${CSS.escape(clearId)}"]`);
  if (!container) return;
  const value = String(query || "").trim();
  if (clear) clear.hidden = !value;
  if (!value) { container.innerHTML = ""; return; }
  const results = searchLibrary(value, appId);
  if (!results.length) {
    container.innerHTML = emptyState(`No matches for “${value}”. Try an app name, topic, or shorter phrase.`);
    return;
  }
  container.innerHTML = `<div class="search-results-grid">${results.map((result) => `<a class="search-result" href="${resultHref(result)}">
    ${result.appId ? renderAppLogo(APP_DATA.find((item) => item.id === result.appId), "search-app-logo") : `<span class="result-icon" aria-hidden="true">${escapeHTML(result.icon)}</span>`}<span class="search-result-copy"><strong>${escapeHTML(result.title)}</strong><span>${escapeHTML(result.detail)}</span></span><span class="result-arrow" aria-hidden="true">→</span>
  </a>`).join("")}</div>`;
  wireImageFallbacks(container);
}

function initPageInteractions() {
  document.addEventListener("input", (event) => {
    const input = event.target.closest("[data-search-input]");
    if (!input) return;
    const scope = input.dataset.searchInput;
    const appId = scope.startsWith("app:") ? scope.slice(4) : "";
    const resultsId = input.id.replace(/-search$/, "-results");
    const clearId = input.id.replace(/-search$/, "");
    renderSearchResults(resultsId, clearId, input.value, appId);
  });

  document.addEventListener("submit", (event) => {
    const form = event.target.closest("[data-search-form]");
    if (!form) return;
    event.preventDefault();
    const input = $("[data-search-input]", form);
    input?.dispatchEvent(new Event("input", { bubbles: true }));
  });

  document.addEventListener("click", async (event) => {
    const clear = event.target.closest("[data-clear-search]");
    if (clear) {
      const input = document.getElementById(`${clear.dataset.clearSearch}-search`);
      if (input) { input.value = ""; input.focus(); input.dispatchEvent(new Event("input", { bubbles: true })); }
      return;
    }

    const queryChip = event.target.closest("[data-query]");
    if (queryChip) {
      const input = $("#home-search");
      if (input) { input.value = queryChip.dataset.query || ""; input.dispatchEvent(new Event("input", { bubbles: true })); input.focus(); }
      return;
    }

    const categoryType = event.target.closest("[data-category-type].filter-button");
    if (categoryType) {
      const selected = categoryType.dataset.categoryType;
      $$("[data-category-type].filter-button").forEach((button) => button.setAttribute("aria-pressed", String(button === categoryType)));
      $$(".category-card").forEach((card) => { card.hidden = selected !== "all" && card.dataset.categoryType !== selected; });
      return;
    }

    const topicFilter = event.target.closest("[data-topic-filter]");
    if (topicFilter) {
      const category = TUTORIAL_CATEGORIES.find((item) => item.id === pageParam());
      const filter = topicFilter.dataset.topicFilter;
      $$("[data-topic-filter]").forEach((button) => button.setAttribute("aria-pressed", String(button === topicFilter)));
      const matches = category ? categoryItems(category) : [];
      const visible = matches.filter((item) => filter === "All" || item.category === filter);
      $("#category-tutorials").innerHTML = visible.length ? visible.map(renderCategoryItem).join("") : emptyState("No tutorials match this topic yet.");
      wireImageFallbacks($("#category-tutorials"));
      prepareReveals($("#category-tutorials"));
      return;
    }

    const copy = event.target.closest("[data-copy]");
    if (copy) {
      const text = copy.dataset.copy || "";
      try {
        if (navigator.clipboard?.writeText) await navigator.clipboard.writeText(text);
        else {
          const textarea = document.createElement("textarea");
          textarea.value = text; textarea.setAttribute("readonly", ""); textarea.style.position = "fixed"; textarea.style.opacity = "0";
          document.body.append(textarea); textarea.select();
          const success = document.execCommand("copy"); textarea.remove();
          if (!success) throw new Error("Clipboard copy failed");
        }
        copy.textContent = "Copied!"; copy.classList.add("copied");
        window.setTimeout(() => { copy.textContent = "Copy"; copy.classList.remove("copied"); }, 1600);
      } catch {
        copy.textContent = "Select text";
        window.setTimeout(() => { copy.textContent = "Copy"; }, 1800);
      }
    }
  });
}

let revealObserver;
function prepareReveals(root = document) {
  const items = $$(".reveal:not(.is-visible)", root);
  if (!items.length) return;
  const reduce = window.matchMedia?.("(prefers-reduced-motion: reduce), (max-width: 760px), (pointer: coarse)").matches;
  if (reduce || !("IntersectionObserver" in window)) {
    items.forEach((item) => item.classList.add("is-visible"));
    return;
  }
  if (!revealObserver) {
    revealObserver = new IntersectionObserver((entries, observer) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      });
    }, { threshold: 0.08, rootMargin: "0px 0px -18px 0px" });
  }
  items.forEach((item, index) => {
    item.style.setProperty("--reveal-delay", `${Math.min(index % 5, 4) * 50}ms`);
    revealObserver.observe(item);
  });
}

