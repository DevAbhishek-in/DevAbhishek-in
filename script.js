function safeMediaURL(value = "") {
  const url = String(value).trim();
  if (!url || /^(javascript|data|vbscript):/i.test(url)) return "";
  if (/^https:\/\//i.test(url)) return safeExternalURL(url);
  if (/^(assets|images)\//.test(url) || /^\.\.?\//.test(url)) return url;
  return "";
}

function safeExternalURL(value = "") {
  const url = String(value).trim();
  if (!/^https:\/\//i.test(url)) return "";
  try {
    const parsed = new URL(url);
    return parsed.protocol === "https:" && parsed.hostname && !parsed.username && !parsed.password ? parsed.href : "";
  } catch {
    return "";
  }
}

