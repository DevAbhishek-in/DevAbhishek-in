function getTutorialContent(item) {
  if (!item) return [];
  const customContent = Array.isArray(item.content) ? item.content.filter((entry) => {
    if (!entry || typeof entry !== "object") return false;
    if (entry.type === "step" || entry.type === "videoNotice") return Boolean(String(entry.text || "").trim());
    if (entry.type === "link" || entry.type === "download") return Boolean(safeExternalURL(entry.url));
    if (entry.type === "command") return Boolean(String(entry.code || "").trim());
    if (entry.type === "image") return Boolean(safeMediaURL(entry.src));
    if (entry.type === "video") return Boolean(videoEmbedURL(entry.url));
    return false;
  }) : [];

  // An ordered content list is the single source of truth when it has valid entries.
  // Existing guides without it continue to use their original, separate arrays.
  if (customContent.length) return customContent;

  const legacyContent = [];
  (Array.isArray(item.steps) ? item.steps : []).forEach((step) => {
    if (String(step || "").trim()) legacyContent.push({ type: "step", text: String(step) });
  });
  (Array.isArray(item.commands) ? item.commands : []).forEach((command) => {
    if (renderCommand(command)) legacyContent.push({ type: "command", label: command?.label, code: typeof command === "string" ? command : command?.code });
  });
  (Array.isArray(item.images) ? item.images : []).forEach((image) => {
    if (image && safeMediaURL(image.src)) legacyContent.push({ type: "image", ...image });
  });
  if (videoEmbedURL(item.videoUrl)) legacyContent.push({ type: "video", url: item.videoUrl });
  (Array.isArray(item.resourceLinks) ? item.resourceLinks : []).forEach((link) => {
    if (link && safeExternalURL(link.url)) legacyContent.push({ type: "link", ...link });
  });
  (Array.isArray(item.downloads) ? item.downloads : []).forEach((download) => {
    if (download && safeExternalURL(download.url)) legacyContent.push({ type: "download", ...download });
  });
  return legacyContent;
}

function renderOrderedContent(item, heading) {
  const entries = getTutorialContent(item);
  if (!entries.length) return "";

  let html = `<div class="detail-block tutorial-content"><h2>${escapeHTML(heading)}</h2><div class="ordered-content">`;
  let stepNumber = 0;

  for (let index = 0; index < entries.length;) {
    const entry = entries[index];
    if (entry.type === "step") {
      const steps = [];
      while (index < entries.length && entries[index].type === "step") {
        steps.push(`<li class="tutorial-step">${escapeHTML(entries[index].text)}</li>`);
        index += 1;
      }
      html += `<ol class="tutorial-steps" style="counter-reset: lesson-step ${stepNumber}">${steps.join("")}</ol>`;
      stepNumber += steps.length;
      continue;
    }

    if (entry.type === "command") html += renderCommand(entry);
    if (entry.type === "link") {
      const url = safeExternalURL(entry.url);
      if (url) html += `<div class="detail-actions ordered-resource"><a class="button button-quiet" href="${escapeHTML(url)}" target="_blank" rel="noopener noreferrer">${escapeHTML(entry.label || "Open resource")} ↗</a></div>`;
    }
    if (entry.type === "download") {
      const url = safeExternalURL(entry.url);
      if (url) html += `<div class="detail-actions ordered-resource"><a class="button button-quiet" href="${escapeHTML(url)}" download>${escapeHTML(entry.label || "Download")} ↓</a></div>`;
    }
    if (entry.type === "image") {
      const image = entry;
      html += `<div class="media-grid ordered-media"><figure class="media-figure">${renderImage(image.src, image.alt || item.title || "Tutorial image", "detail-media")}${image.caption ? `<figcaption>${escapeHTML(image.caption)}</figcaption>` : ""}</figure></div>`;
    }
    if (entry.type === "video") {
      const url = videoEmbedURL(entry.url);
      if (url) html += `<div class="video-frame ordered-video"><iframe src="${escapeHTML(url)}" title="${escapeHTML(item.title || "Tutorial")} video" loading="lazy" referrerpolicy="strict-origin-when-cross-origin" allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share" allowfullscreen></iframe></div>`;
    }
    if (entry.type === "videoNotice") {
      html += `<aside class="detail-note video-notice"><strong>${escapeHTML(entry.title || "Video note")}</strong><p>${escapeHTML(entry.text)}</p></aside>`;
    }
    index += 1;
  }

  return `${html}</div></div>`;
}

