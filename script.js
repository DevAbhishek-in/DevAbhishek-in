function categoryItems(category) {
  const tutorials = TUTORIAL_DATA.filter((item) => hasRecordId(item) && (category.appId
    ? item.appId === category.appId
    : item.categoryId === category.id || item.category === category.category
  ));
  const guides = SETUP_GUIDE_DATA.filter((item) => hasRecordId(item) && (category.appId
    ? item.appId === category.appId
    : item.category === category.category
  ));
  return [
    ...tutorials.map((item) => ({ ...item, recordType: "tutorial" })),
    ...guides.map((item) => ({ ...item, recordType: "guide" }))
  ];
}

function renderCategoryItem(item) {
  return item.recordType === "guide" ? renderGuideCard(item) : renderTutorialCard(item);
}

function categoryStatus(category, app, matching = categoryItems(category)) {
  if (matching.some((item) => normalizedStatus(item.status) === "available")) return "available";
  if (matching.length) return "coming soon";
  if (category.status) return normalizedStatus(category.status);
  return appStatus(app);
}

